def _compile(items):
    out = []
    for it in items:
        main, _, ctx = it.partition('&')
        out.append((lex_pattern(main), lex_pattern(ctx.replace('|', ' ')) if ctx else None))
    return out


_ET = {et: _compile(v[1]) for et, v in EVENT_TYPES.items()}
_SEC = {s: _compile(ws) for s, ws in SECTOR_LEXICON.items()}
_COMM = {c: _compile(ws) for c, ws in COMMODITIES.items()}
_NONBIZ = _compile(NON_BUSINESS)
_RFREG = {name: lex_pattern(p) for name, p in RF_REGIONS.items()}
_FOREIGN = _compile(FOREIGN_CUES)
_RUSSIA = _compile(RUSSIA_CUES)


def _has_ctx(ctx, toks: list[str]) -> bool:
    """Контекст 'A&B': хотя бы одно слово из B встречается в тексте."""
    return any(lex_count(((w,),), toks) for alts in ctx for w in alts)


def _lex_score(compiled, t_title: list[str], t_body: list[str]) -> float:
    s = 0.0
    all_t = t_title + t_body
    for pat, ctx in compiled:
        if ctx and not _has_ctx(ctx, all_t):
            continue
        s += 2.0 * lex_count(pat, t_title) + 0.5 * min(3, lex_count(pat, t_body))
    return s


def _any(compiled, toks: list[str]) -> bool:
    return any(lex_count(pat, toks) for pat, _ in compiled)


def clean_body(body: str) -> str:
    for rx in BOILERPLATE:
        body = rx.sub(' ', body)
    return body.strip()


def _stems(phrase: str) -> list[str]:
    return [stem(w) for w in re.findall(r'[a-zа-яё0-9-]+', phrase.lower())]


def _count(stem_list: list[str], text_stems: list[str]) -> int:
    """Число вхождений фразы (последовательности префиксов стеммов) в тексте — для регионов из профилей."""
    n = len(stem_list)
    if not n:
        return 0
    hits = 0
    for i in range(len(text_stems) - n + 1):
        if all(text_stems[i + j].startswith(stem_list[j]) for j in range(n)):
            hits += 1
    return hits


def _region_index(regions: list[str]) -> dict[str, str]:
    idx = {}
    for r in regions:
        key = [s for s in _stems(r) if s not in ('област', 'край', 'республик', 'автоном', 'округ', 'г')]
        if key:
            idx[' '.join(key)] = r
    return idx


def _direction_in(sentence: str) -> str | None:
    low = sentence.lower()
    for d, words in DIRECTION.items():
        if any(w in low for w in words):
            return d
    return None


def detect_direction(title: str, body: str, event_type: str | None = None) -> str | None:
    """Направление: приоритетно по заголовку, затем по первому предложению, затем по остальному тексту.
    Отрицание в том же предложении («снижения не будет», «не ожидает роста») превращает up/down в hold для
    ставки или в «не указано» для остальных событий."""
    sents = sentences(body)
    candidates = [title] + sents[:1] + sents[1:]
    for s in candidates:
        d = _direction_in(s)
        if d is None:
            continue
        if d in ('up', 'down') and NEGATION.search(s):
            return 'hold' if event_type == 'key_rate' else None
        return d
    return None


def extract_event(news: dict, regions: list[str] | None = None) -> dict:
    title = news.get('title') or ''
    body = clean_body(news.get('content') or news.get('summary') or '')
    text = f'{title}. {body}'
    l_title, l_body = lex_tokens(title), lex_tokens(body)
    t_title = tokens(title, drop_stop=False)
    t_body = tokens(body, drop_stop=False)
    low = text.lower()

    scores = {et: s for et, comp in _ET.items() if (s := _lex_score(comp, l_title, l_body))}
    sec_scores = {sec: s for sec, comp in _SEC.items() if (s := _lex_score(comp, l_title, l_body)) >= 0.5}
    non_business = sum(lex_count(pat, l_title + l_body) for pat, _ in _NONBIZ)

    ranked = sorted(scores.items(), key=lambda x: -x[1])
    business_signal = (ranked[0][1] if ranked else 0) + sum(sec_scores.values()) * 0.5
    if not ranked and not sec_scores:
        event_type = 'non_business'
    elif non_business >= 1 and business_signal < 2.5:
        event_type = 'non_business'
    elif ranked and ranked[0][1] >= 1.0:
        event_type = ranked[0][0]
    elif sec_scores:
        event_type = 'industry'
    else:
        event_type = 'non_business'

    secondary = [et for et, s in ranked[1:4] if s >= 1.0]
    channels: dict[str, float] = {}
    for et in [event_type] + secondary:
        if et in EVENT_TYPES:
            w = 1.0 if et == event_type else 0.5
            for ch, v in EVENT_TYPES[et][2].items():
                channels[ch] = round(max(channels.get(ch, 0), v * w), 3)

    direction = detect_direction(title, body, event_type)
    commodities = [c for c, comp in _COMM.items() if _lex_score(comp, l_title, l_body) >= 0.5]

    region_hits = []
    idx = _region_index(regions or [])
    all_stems = t_title + t_body
    for key, name in idx.items():
        if _count(key.split(), all_stems):
            region_hits.append(name)
    districts = [v for k, v in FED_DISTRICTS.items() if f'{k} федеральн' in low]
    regions_mentioned = [name for name, pat in _RFREG.items() if lex_count(pat, l_title)]
    all_l = l_title + l_body
    if _any(_FOREIGN, all_l) and not _any(_RUSSIA, all_l) and not regions_mentioned and not region_hits:
        geo_scope = 'foreign'
    elif regions_mentioned:
        geo_scope = 'regional'
    else:
        geo_scope = 'national'

    participants = [p for p in PARTICIPANTS if re.search(rf'(?<![А-Яа-яё]){re.escape(p)}(?![а-яё])', text)]
    participants += [m.strip() for m in re.findall(r'«([^»]{2,40})»', text)][:5]

    evidence = []
    trig = _ET.get(event_type, [])
    for s in sentences(text)[:12]:
        if looks_like_injection(s):
            continue
        st = lex_tokens(s)
        if any(lex_count(pat, st) for pat, _ in trig) or re.search(r'\d', s):
            evidence.append({'quote': s[:400], 'source_id': f'N:{news.get("id", "")}'})
        if len(evidence) >= 3:
            break
    event_date = None
    m = re.search(r'\((\d{2})\.(\d{2})\.(20\d{2})\)', title)
    if m:
        event_date = f'{m.group(3)}-{m.group(2)}-{m.group(1)}'

    label = EVENT_TYPES[event_type][0] if event_type in EVENT_TYPES else (
        'Отраслевое событие' if event_type == 'industry' else 'Не относится к бизнесу')
    importance = EVENT_TYPES[event_type][3] if event_type in EVENT_TYPES else (0.2 if event_type == 'industry' else 0.0)
    return {
        'event_type': event_type,
        'event_label': label,
        'secondary_types': secondary,
        'sectors': [s for s, _ in sorted(sec_scores.items(), key=lambda x: -x[1])][:4],
        'sector_labels': [SECTORS[s] for s, _ in sorted(sec_scores.items(), key=lambda x: -x[1])][:4],
        'channels': channels,
        'commodities': commodities,
        'direction': direction,
        'regions': region_hits[:5],
        'regions_mentioned': regions_mentioned[:5],
        'geo_scope': geo_scope,
        'federal_districts': districts,
        'participants': participants[:8],
        'published_at': news.get('published_at'),
        'event_date': event_date,
        'macro_importance': importance,
        'bank_topics': EVENT_TYPES[event_type][4] if event_type in EVENT_TYPES else [],
        'evidence': evidence,
        'business_relevant': event_type != 'non_business',
        'extractor': EXTRACTOR_VERSION,
        'suspicious_instructions': looks_like_injection(text),
        'unknown': [f for f, v in (('event_date', event_date), ('regions', region_hits), ('direction', direction)) if not v],
    }


def bank_query(event: dict, news: dict) -> str:
    """Запрос в аналитику банка: тип события + ключевые слова заголовка."""
    parts = [news.get('title', '')]
    if event['event_type'] in EVENT_TYPES:
        parts.append(EVENT_TYPES[event['event_type']][0])
    parts += event.get('sector_labels', [])[:2]
    return ' '.join(parts)


def parse_dt(value) -> datetime | None:
    if not value:
        return None
    if isinstance(value, datetime):
        return value
    try:
        return datetime.fromisoformat(str(value).replace('Z', '+00:00'))
    except ValueError:
        return None
