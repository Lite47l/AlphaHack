def find(channel: str, event_type: str, direction: str | None) -> dict | None:
    return M.get((channel, event_type, direction or '*')) or M.get((channel, event_type, '*'))


def candidates(event: dict, profile: dict, limit: int = 4) -> list[dict]:
    """Применимые механизмы: канал есть у компании и есть шаблон для типа события."""
    out = []
    types = [event['event_type']] + event.get('secondary_types', [])
    weights = event.get('channels', {})
    for et in types:
        # порядок — по силе влияния ИМЕННО этого события на канал компании (вес канала события × сила канала)
        for ch_key, ch in sorted(profile['channels'].items(), key=lambda x: -(weights.get(x[0], 0.1) * x[1]['strength'])):
            m = find(ch_key, et, event.get('direction'))
            if ch_key == 'fuel_costs' and et == 'fuel_energy' and any(s['key'] == 'fuel_energy' for s in profile['sectors']):
                m = M[('fuel_costs', 'fuel_energy', '*')]  # для продавца топлива рост цен — не только издержки
            if m and all(o['channel'] != ch_key for o in out):
                out.append({'channel': ch_key, 'channel_label': ch['label'], 'event_type': et, 'basis': ch['basis'],
                            'notes': ch['notes'], 'strength': ch['strength'], **m})
    if event['event_type'] in ('key_rate', 'credit_market') and 'cost_of_debt' not in profile['channels'] \
            and profile['products'].get('CL_PRODUCT_LOA_MARK') == 0 and profile['products'].get('CL_PRODUCT_LEA_MARK') == 0:
        out.append({**NO_DEBT, 'event_type': event['event_type']})
    for m in out:
        m['gap'] = GAPS.get(m['channel'], '')
    return out[:limit]
